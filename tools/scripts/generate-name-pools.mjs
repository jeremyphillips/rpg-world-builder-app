function toExportName(id) {
  return `${id.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase())}Collection`
}

function renderPool(pool) {
  const genderLine =
    pool.genderStyle === undefined ? '' : `        genderStyle: '${pool.genderStyle}',\n`
  const values = pool.values.map((value) => `          '${value}',`).join('\n')

  return [
    '      {',
    `        id: '${pool.id}',`,
    `        role: '${pool.role}',`,
    genderLine.replace(/\n$/, ''),
    '        values: [',
    values,
    '        ],',
    '      },',
  ]
    .filter((line) => line !== '')
    .join('\n')
}

