function toExportName(id) {
  return `${id.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase())}Collection`
}

function renderPool(pool) {
  const genderLine =
    pool.genderStyle === undefined ? '' : `        genderStyle: '${pool.genderStyle}',\n`
  const values = pool.values.map((value) => `          '${value}',`).join('\n')

  return [
    '      {',
    `        id: '${pool.id}',`,
    `        role: '${pool.role}',`,
    genderLine.replace(/\n$/, ''),
    '        values: [',
    values,
    '        ],',
    '      },',
  ]
    .filter((line) => line !== '')
    .join('\n')
}

function renderProvenance(spec) {
  if (spec.provenanceNotes === undefined) {
    return `FIXTURE_COLLECTION_PROVENANCE.${spec.provenance}`
  }

  const notes = spec.provenanceNotes.replace(/'/g, "\\'")
  return `{
    ...FIXTURE_COLLECTION_PROVENANCE.${spec.provenance},
    notes: '${notes}',
  }`
}

function renderCollection(spec) {
  const subjectKinds = spec.subjectKinds.map((kind) => `'${kind}'`).join(', ')

  return `import type { NameCollection } from '@rpg/contracts/name-generator'

import { FIXTURE_COLLECTION_PROVENANCE } from '../lib/provenance'

// Generated by tools/scripts/generate-name-pools.mjs — edit the morpheme tables there.
export const ${toExportName(spec.id)} = {
  id: '${spec.id}',
  label: '${spec.label}',
  description: '${spec.description}',
  subjectKinds: [${subjectKinds}],
  generator: {
    type: 'sample',
    pools: [
${spec.pools.map(renderPool).join('\n')}
    ],
  },
  provenance: ${renderProvenance(spec)},
  version: 1,
} as const satisfies NameCollection
`
}

function main() {
  const specs = [
    ...buildPlaceCollections(),
    ...buildHeritageGivenCollections(),
    ...FACTION_COLLECTIONS,
    ...AKAN_COLLECTIONS,
    ...REAL_WORLD_COLLECTIONS,
  ]

  mkdirSync(COLLECTIONS_DIR, { recursive: true })

  for (const spec of specs) {
    writeFileSync(join(COLLECTIONS_DIR, `${spec.id}.ts`), renderCollection(spec), 'utf8')
    const total = spec.pools.reduce((sum, pool) => sum + pool.values.length, 0)
    console.log(`${spec.id}\t${total}`)
  }

  console.log(`\n${specs.length} collections written to ${COLLECTIONS_DIR}`)
}

main()
