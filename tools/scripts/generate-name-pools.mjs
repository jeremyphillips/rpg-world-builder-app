#!/usr/bin/env node
// Regenerates the composed name-generator collection assets in
// packages/name-generator-data/src/collections.
//
// Head pools (place roots, faction descriptors/emblems, heritage given names) are
// composed from morpheme tables and down-sampled evenly across the sorted set so
// every pool spans the alphabet. Suffix and vocabulary pools are authored inline.
//
// Usage: node tools/scripts/generate-name-pools.mjs
//
// Re-run after editing a morpheme table, then format with
// `pnpm prettier --write packages/name-generator-data/src/collections`.

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const COLLECTIONS_DIR = join(HERE, '../../packages/name-generator-data/src/collections')

const HEAD_POOL_SIZE = 300
const GENDERED_POOL_SIZE = 150

// ---------------------------------------------------------------------------
// Composition helpers
// ---------------------------------------------------------------------------

function compose(heads, tails) {
  return heads.flatMap((head) => tails.map((tail) => `${head}${tail}`))
}

/** Dedupes, sorts, then keeps `size` entries spread evenly across the sorted set. */
function selectSpread(values, size) {
  const unique = [...new Set(values)].sort((left, right) => left.localeCompare(right))
  if (unique.length < size) {
    throw new Error(`Need ${size} values, morpheme tables only produce ${unique.length}`)
  }

  const step = unique.length / size
  const picked = []
  for (let index = 0; index < size; index += 1) {
    picked.push(unique[Math.floor(index * step)])
  }

  return picked
}

function sorted(values) {
  const unique = [...new Set(values)].sort((left, right) => left.localeCompare(right))
  if (unique.length !== values.length) {
    throw new Error(`Duplicate values in authored pool: ${values.length - unique.length} repeats`)
  }
  return unique
}

function composedPool({ id, role, heads, tails, size = HEAD_POOL_SIZE, genderStyle }) {
  return { id, role, genderStyle, values: selectSpread(compose(heads, tails), size) }
}

function authoredPool({ id, role, values, genderStyle }) {
  return { id, role, genderStyle, values: sorted(values) }
}

