const RULESET = 'srd-cc-5.2.1'
const TS = '2024-05-21T00:00:00.000Z'

function base(slug, name, description, cost, weight, kind, extra) {
  const item = {
    id: `${RULESET}:${slug}`,
    slug,
    rulesetId: RULESET,
    source: 'system',
    campaignId: null,
    createdAt: TS,
    updatedAt: TS,
    name,
    description,
    cost,
    kind,
    ...extra,
  }
  if (weight !== undefined) item.weight = weight
  return item
}

const lb = (value) => ({ value, unit: 'lb' })
const gp = (amount) => ({ amount, currency: 'gp' })
const sp = (amount) => ({ amount, currency: 'sp' })
const cp = (amount) => ({ amount, currency: 'cp' })

function gear(slug, name, description, cost, weight, gearKind, extra = {}) {
  const spellcastingSubKinds = new Set([
    'arcane_focus',
    'druidic_focus',
    'holy_symbol',
    'spellbook',
    'component_pouch',
  ])
  if (spellcastingSubKinds.has(gearKind)) {
    return base(slug, name, description, cost, weight, 'adventuring_gear', {
      gearKind: 'spellcasting',
      spellcastingGearKind: gearKind,
      ...extra,
    })
  }
  return base(slug, name, description, cost, weight, 'adventuring_gear', { gearKind, ...extra })
}

function magic(slug, name, descriptionHtml, cost, weight, extra) {
  return base(slug, name, descriptionHtml, cost, weight, 'magic_item', extra)
}

